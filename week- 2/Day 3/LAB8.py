message = "Python Programming"

first_char = message[0]
last_char = message[-1]

print(f"First character is {first_char} and last character is {last_char}")

sliced_message = message[:6]
reversed_message = message[::-1]

print(f"My message was {message}")
print(f"If we take the first 6 characters it will be {sliced_message}")
print(f"If we reverse it, it will be {reversed_message}")

